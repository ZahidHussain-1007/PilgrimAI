const DICT: Record<AppLanguage, Entry> = { en: EN, te: TE, hi: HI }

export const I18N_LANGUAGES: AppLanguage[] = ["en", "te", "hi"]

export function translate(lang: AppLanguage, key: string): string {
  return DICT[lang]?.[key] || EN[key] || key
}

/** Live-translating hook: re-renders when the language chips change. */
export function useT(): { lang: AppLanguage; t: (key: string) => string } {
  useEffect(() => {
    // testing/override hook: /?lang=te sets the stored language once
    const param = new URLSearchParams(window.location.search).get("lang")
    if (
      param &&
      (param === "en" || param === "te" || param === "hi") &&
      getStoredLanguage() !== param
    ) {
      setStoredLanguage(param as AppLanguage)
      const url = new URL(window.location.href)
      url.searchParams.delete("lang")
      window.location.replace(url.toString())
    }
  }, [])

  const [lang, setLang] = useState<AppLanguage>("en")
  useEffect(() => {
    const sync = () => setLang(getStoredLanguage())
    sync()
    window.addEventListener("pilgrim:language-changed", sync)
    window.addEventListener("storage", sync)
    return () => {
      window.removeEventListener("pilgrim:language-changed", sync)
      window.removeEventListener("storage", sync)
    }
  }, [])
  return { lang, t: (key: string) => translate(lang, key) }
}
